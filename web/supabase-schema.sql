-- Execute no SQL Editor de um projeto Supabase.
-- Cada registro pertence ao usuário autenticado e fica protegido por RLS.

create extension if not exists pgcrypto;

create table if not exists public.contacts (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  data jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.activities (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  contact_id uuid references public.contacts(id) on delete set null,
  title text not null,
  activity_date date not null,
  activity_time time,
  activity_type text not null default 'Follow-up',
  notes text not null default '',
  completed boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.weekly_goals (
  user_id uuid not null references auth.users(id) on delete cascade,
  week_start date not null,
  target integer not null default 20 check (target between 1 and 200),
  updated_at timestamptz not null default now(),
  primary key (user_id, week_start)
);

create table if not exists public.ai_usage (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  provider text not null default 'openai',
  model text not null,
  mode text not null,
  input_tokens integer not null default 0,
  output_tokens integer not null default 0,
  created_at timestamptz not null default now()
);

create index if not exists ai_usage_user_month_idx
  on public.ai_usage (user_id, created_at desc);

alter table public.contacts enable row level security;
alter table public.activities enable row level security;
alter table public.weekly_goals enable row level security;
alter table public.ai_usage enable row level security;

drop policy if exists "contacts_own_rows" on public.contacts;
drop policy if exists "activities_own_rows" on public.activities;
drop policy if exists "weekly_goals_own_rows" on public.weekly_goals;
drop policy if exists "ai_usage_own_rows" on public.ai_usage;

create policy "contacts_own_rows" on public.contacts
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "activities_own_rows" on public.activities
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "weekly_goals_own_rows" on public.weekly_goals
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "ai_usage_own_rows" on public.ai_usage
  for select using (auth.uid() = user_id);

do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'contacts'
  ) then
    alter publication supabase_realtime add table public.contacts;
  end if;
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'activities'
  ) then
    alter publication supabase_realtime add table public.activities;
  end if;
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'weekly_goals'
  ) then
    alter publication supabase_realtime add table public.weekly_goals;
  end if;
end $$;
